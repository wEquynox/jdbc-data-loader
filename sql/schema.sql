CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    building VARCHAR(150) NOT NULL,
    room VARCHAR(50) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    accessible BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (building, room)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    organizer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    venue_id BIGINT NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    period TSTZRANGE GENERATED ALWAYS AS (
        tstzrange(starts_at, ends_at, '[)')
    ) STORED,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'completed', 'cancelled')),
    tags TEXT[] NOT NULL DEFAULT '{}',
    metadata JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (ends_at > starts_at)
);

CREATE TABLE registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'registered'
        CHECK (status IN ('registered', 'attended', 'cancelled')),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, event_id),
    UNIQUE (user_id, event_id, status)
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (length(trim(body)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    registration_status VARCHAR(20) NOT NULL DEFAULT 'attended'
        CHECK (registration_status = 'attended'),
    score SMALLINT NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, event_id),
    FOREIGN KEY (user_id, event_id, registration_status)
        REFERENCES registrations(user_id, event_id, status)
        ON DELETE CASCADE
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(100) NOT NULL,
    entity_id TEXT NOT NULL,
    action VARCHAR(10) NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data JSONB,
    new_data JSONB,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE FUNCTION audit_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    old_row JSONB;
    new_row JSONB;
    row_data JSONB;
    row_id TEXT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        old_row := to_jsonb(OLD);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        new_row := to_jsonb(NEW);
    END IF;

    row_data := COALESCE(new_row, old_row);
    row_id := row_data ->> 'id';

    INSERT INTO audit_log (
        table_name,
        entity_id,
        action,
        old_data,
        new_data
    )
    VALUES (
        TG_TABLE_NAME,
        row_id,
        TG_OP,
        old_row,
        new_row
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER events_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON events
FOR EACH ROW
EXECUTE FUNCTION audit_row_change();

CREATE TRIGGER registrations_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON registrations
FOR EACH ROW
EXECUTE FUNCTION audit_row_change();

CREATE FUNCTION validate_rating()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    event_end TIMESTAMPTZ;
BEGIN
    SELECT e.ends_at
    INTO event_end
    FROM events e
    WHERE e.id = NEW.event_id;

    IF event_end IS NULL THEN
        RAISE EXCEPTION 'Event % does not exist', NEW.event_id;
    END IF;

    IF event_end > NOW() THEN
        RAISE EXCEPTION 'Ratings can only be submitted after the event ends';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER ratings_validation_trigger
BEFORE INSERT OR UPDATE ON ratings
FOR EACH ROW
EXECUTE FUNCTION validate_rating();

CREATE VIEW event_summary AS
SELECT
    e.id AS event_id,
    e.title,
    e.starts_at,
    e.ends_at,
    e.status,
    e.capacity,
    v.name AS venue_name,
    COUNT(r.id) FILTER (WHERE r.status IN ('registered', 'attended')) AS registered_count,
    ROUND(AVG(rt.score)::NUMERIC, 2) AS average_rating
FROM events e
JOIN venues v ON v.id = e.venue_id
LEFT JOIN registrations r ON r.event_id = e.id
LEFT JOIN ratings rt ON rt.event_id = e.id
GROUP BY
    e.id,
    e.title,
    e.starts_at,
    e.ends_at,
    e.status,
    e.capacity,
    v.name;

CREATE FUNCTION event_occupancy(p_event_id BIGINT)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    event_capacity INTEGER;
    registered_count BIGINT;
BEGIN
    SELECT capacity
    INTO event_capacity
    FROM events
    WHERE id = p_event_id;

    IF event_capacity IS NULL THEN
        RAISE EXCEPTION 'Event % does not exist', p_event_id;
    END IF;

    SELECT COUNT(*)
    INTO registered_count
    FROM registrations
    WHERE event_id = p_event_id
      AND status IN ('registered', 'attended');

    RETURN ROUND((registered_count::NUMERIC / event_capacity) * 100, 2);
END;
$$;

CREATE PROCEDURE cancel_registration(
    p_user_id BIGINT,
    p_event_id BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE registrations
    SET status = 'cancelled'
    WHERE user_id = p_user_id
      AND event_id = p_event_id
      AND status = 'registered';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'No active registration found for user % and event %',
            p_user_id,
            p_event_id;
    END IF;
END;
$$;

